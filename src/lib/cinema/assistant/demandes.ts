import type { CinemaDuFilm } from "../../../../remotion/film/cinema/types";
import { referencesDeLaSerie } from "../bible/etat";
import { LIMITES_DU_SCENARIO, demandeDeScenario, type DemandeDeScenario } from "../scenario-demande";
import { type MarqueDuFilm, laBible, leCasting, lEpisode, leProduit, lesEpisodesPrecedents, ligneDeLaMarque } from "./contexte";
import type { DemandeALAssistant } from "./types";

/**
 * Ce qu'on demande à Claude pour UN geste de l'assistant (une réplique, une
 * consigne, les dialogues d'une scène, le plan suivant, l'épisode suivant).
 * Module pur. Les visuels en anglais (Veo les suit mieux), les répliques en
 * français, et toujours la série entière en contexte.
 */
export const REPLIQUE_DEMANDEE = 100;

const REGLES = [
  "You help write a short vertical drama series for a brand's social media. Each shot is generated by a video AI (Veo) and lasts 8 seconds.",
  "Rules:",
  "- Shot actions are in ENGLISH, concrete and visual (what the camera sees), one or two sentences, consistent with the scene's setting.",
  `- Lines of dialogue are in FRENCH, natural and spoken, at most ${REPLIQUE_DEMANDEE} characters (8 seconds), said by a character who is ON SCREEN in that shot.`,
  "- Stay consistent with the story, the characters and the tone of the rest of the episode.",
  "- Never put text, logos or brand names in the image. Never invent facts about the product (no health or performance claims).",
  "Answer with ONE JSON object and nothing else.",
].join("\n");

// Une réplique existe déjà : on en veut une AUTRE (la recette du 15/10 l'a vu
// recopier mot pour mot la réplique en place).
const UNE_AUTRE = "If a line already exists, write a DIFFERENT one: never repeat the current wording.";
const UNE_AUTRE_DESCRIPTION = "If a description already exists, write a DIFFERENT one: never repeat the current wording.";

const QUOI_DECRIRE: Record<"personnage" | "creature" | "objet" | "decor", { quoi: string; style: string }> = {
  personnage: { quoi: "a character", style: "Describe their physical appearance AND outfit in one or two concrete sentences, the way a casting reference sheet would." },
  creature: { quoi: "a creature", style: "Describe its anatomy, colors and distinctive features in one or two concrete sentences, the way a creature reference sheet would." },
  objet: { quoi: "an object", style: "Describe its shape, material and colors in one or two concrete sentences, the way a props reference sheet would." },
  decor: { quoi: "a location", style: "Describe what it looks like (architecture, light, mood) in one or two concrete sentences, the way an art department reference sheet would." },
};

function contexte(marque: MarqueDuFilm, cinema: CinemaDuFilm, episodeId: string, cible: { scene?: string; plan?: string }): string {
  const episode = cinema.episodes.find((e) => e.id === episodeId);
  return [ligneDeLaMarque(marque), leCasting(cinema), leProduit(cinema), episode ? lEpisode(cinema, episode, cible) : ""].filter(Boolean).join("\n\n");
}

export function demandeALAssistant(marque: MarqueDuFilm, cinema: CinemaDuFilm, demande: DemandeALAssistant): DemandeDeScenario {
  const { systeme, message } = demandeSansHistorique(marque, cinema, demande);
  const ecartees = demande.aEviter ?? [];
  if (ecartees.length === 0) return { systeme, message };
  return { systeme, message: `${message}\n\nAlready proposed and rejected by the user, write something clearly different:\n${ecartees.map((t) => `- ${t}`).join("\n")}` };
}

function demandeSansHistorique(marque: MarqueDuFilm, cinema: CinemaDuFilm, demande: DemandeALAssistant): DemandeDeScenario {
  switch (demande.type) {
    case "replique":
      return {
        systeme: `${REGLES}\nFormat: {"personnage": first name of a character on screen in THIS SHOT, "texte": the French line}`,
        message: `${contexte(marque, cinema, demande.episode, { plan: demande.plan })}\n\nWrite the line of dialogue for THIS SHOT. The user explicitly asked for one: you MUST write a non-empty line, even if the character is alone (she can speak to herself, to someone off screen, or softly to the camera). ${UNE_AUTRE}`,
      };
    case "consigne":
      return {
        systeme: `${REGLES}\nFormat: {"consigne": the English action of THIS SHOT}`,
        message: `${contexte(marque, cinema, demande.episode, { plan: demande.plan })}\n\nWrite (or rewrite, more visual and precise) the action of THIS SHOT. Keep who is on screen and whether the product is visible.`,
      };
    case "dialogues":
      return {
        systeme: `${REGLES}\nFormat: {"repliques": [{"plan": shot number in THIS SCENE, "personnage": first name on screen in that shot, "texte": French line}]} — a shot with nobody on screen stays silent and is omitted.`,
        message: `${contexte(marque, cinema, demande.episode, { scene: demande.scene })}\n\nWrite the dialogue of THIS SCENE, shot by shot, as one coherent exchange. Give a line to every shot where a character is on screen, unless silence clearly serves the story. The scene must have at least one line. ${UNE_AUTRE}`,
      };
    case "plan-suivant":
      return {
        systeme: `${REGLES}\nFormat: {"consigne": English action, "personnages": [first names on screen, at most 3, existing characters only], "objet": boolean (is the product visible), "replique": {"personnage": first name on screen, "texte": French line} | null}`,
        message: `${contexte(marque, cinema, demande.episode, { scene: demande.scene })}\n\nPropose the NEXT shot at the end of THIS SCENE: what naturally comes next in the story.`,
      };
    case "decrire-reference": {
      const reference = referencesDeLaSerie(cinema).find((r) => r.id === demande.reference);
      const nom = reference?.nom ?? demande.reference;
      const { quoi, style } = QUOI_DECRIRE[reference?.type ?? "personnage"];
      return {
        systeme: [
          "You write visual reference descriptions for an AI video generator (Veo). Each description is repeated word for word in every shot that uses it: it must stay short, concrete and visually consistent.",
          `You are describing ${quoi} named "${nom}".`,
          style,
          "Write in ENGLISH (Veo follows it better). No text, no logo, no brand name. This is a FICTIONAL reference, never describe a real identifiable person.",
          'Answer with ONE JSON object and nothing else.\nFormat: {"description": the English description}',
        ].join("\n"),
        message: `${ligneDeLaMarque(marque)}\n\n${leProduit(cinema)}\n\n${laBible(cinema)}\n\nWrite (or rewrite, more concrete) ${nom}'s description, consistent with the rest of the references above and with the brand. ${UNE_AUTRE_DESCRIPTION}`,
      };
    }
    case "importer-bible": {
      return {
        systeme: [
          "You read a client's full story bible for a vertical drama series (characters, world, episodes already written or summarized) and extract what a production tool needs to seed the series.",
          "Extract EVERY character (person), creature, object and location that has any visual description, even brief. One entry each. Never invent someone or something that is not in the text.",
          "For characters: an English one- or two-sentence physical description and outfit, the way a casting reference sheet would. For creatures/objects/locations, the same but matching their nature (anatomy, shape and material, or architecture and light).",
          "Also extract a brief for EVERY episode, or scene-by-scene piece, mentioned or summarized in the text, in story order. If the text describes a single clip or video as a whole rather than several episodes, treat it as ONE entry (title = the song or project name if given, else a short descriptive title). Never invent one that is not in the text.",
          "That brief's note starts with one sentence of what happens overall. If the text ALSO gives a shot-by-shot breakdown (a numbered list of shots/plans, each with what it shows), add it right after as a numbered list in the SAME note, one line per shot, each line starting with 'Shot N: ' followed by one concrete visual sentence (what the camera sees, in story order). Keep the whole note under 2000 characters: if the breakdown is longer, keep only its most important shots.",
          `Already known, never repeat them: ${[...cinema.personnages.map((p) => p.nom), ...(cinema.elements ?? []).map((e) => e.nom)].join(", ") || "(nothing yet)"}.`,
          `Episodes already written or already queued, never repeat them: ${[...cinema.episodes.map((e) => e.titre), ...(cinema.episodesAVenir ?? []).map((e) => e.titre)].join(", ") || "(none yet)"}.`,
          "Write descriptions in ENGLISH (Veo follows it better). Keep episode titles and briefs in the language of the source text.",
          "If the text explicitly asks for a dominant visual art style for the images/videos, map it to the single closest match: photorealiste, cinema-fantasy, animation-3d, illustration, or manga-anime (use manga-anime only when the text says manga, anime, or comic-style ink art). Omit the field if no style is described.",
          "If the text explicitly describes a color palette (which color for which use) or a list of things to avoid / never show, extract each as one short English sentence. Omit either field if not present in the text.",
          'Answer with ONE JSON object and nothing else.\nFormat: {"personnages": [{"nom": string, "description": string}], "elements": [{"type": "creature" | "objet" | "decor", "nom": string, "description": string}], "episodes": [{"titre": string, "note": string}], "style": one of the five values above | null, "palette": string | null, "negatif": string | null}',
        ].join("\n"),
        message: `The client's bible, pasted below. Extract from it only:\n\n${demande.texte}`,
      };
    }
    case "episode-suivant": {
      const brief = demande.note?.trim()
        ? demande.note.trim()
        : "Écris l'épisode suivant : la suite directe de l'histoire, avec le même casting, une nouvelle situation, sans répéter les épisodes précédents.";
      const base = demandeDeScenario({ ...marque, cinema }, brief);
      const L = LIMITES_DU_SCENARIO;
      const limite = `HARD LIMIT, the answer is rejected otherwise: at most ${L.plansAuTotal} shots IN TOTAL across all scenes (count them before answering), at most ${L.scenes} scenes.`;
      return { systeme: `${base.systeme}\n${limite}`, message: `${base.message}\n\nThe episodes already written (continue the story, do not repeat them):\n${lesEpisodesPrecedents(cinema)}\n\n${limite}` };
    }
  }
}
